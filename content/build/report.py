"""Write content/extracted/REPORT.md: counts per extracted dataset and chapter, plus known gaps.
Run after extract_phb.py, parse_spells.py and parse_content.py."""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
EXT = ROOT / "content" / "extracted"
S = EXT / "structured"


def load(name):
    return json.loads((S / f"{name}.json").read_text(encoding="utf-8"))


def main():
    spells, lists, gaps = load("spells"), load("spell-lists"), load("spell-gaps")
    conds, feats, bgs, races = load("conditions"), load("feats"), load("backgrounds"), load("races")
    classes, equip, creatures, gods = load("classes"), load("equipment"), load("creatures"), load("gods")
    by_level = {}
    for s in spells:
        by_level[s["level"]] = by_level.get(s["level"], 0) + 1
    out = ["# Extraction report", "", "Generated by `content/build/report.py`. Counts are what the heuristic parsers found; "
           "compare against the handbook before trusting a dataset.", "", "## Structured datasets", "",
           "| Dataset | Found | Expected | Notes |", "|---|---|---|---|",
           f"| Spells | {len(spells)} | 362 | levels {dict(sorted(by_level.items()))}; descriptions missing from the PDF text layer: {', '.join(gaps['listed_but_no_description_in_pdf'])} |",
           f"| Spell-list entries | {sum(len(v) for l in lists.values() for v in l.values())} | — | per class: {', '.join(f'{c} {sum(len(v) for v in l.values())}' for c, l in lists.items())} |",
           f"| Conditions | {len(conds)} | 15 | includes Exhaustion table text |",
           f"| Feats | {len(feats)} | 42 | |",
           f"| Backgrounds | {len(bgs)} | 13 | |",
           f"| Races + subraces | {len(races)} | 18 | Variant Human traits are not in the PDF text layer |",
           f"| Classes | {len(classes)} | 12 | each with a 20-row level table (`columns` is raw text, not split per column) |",
           f"| Equipment rows | {len(equip)} | — | {sum(1 for r in equip if 'damage' in r)} weapons, {sum(1 for r in equip if 'armorClass' in r)} armor; `category` is the nearest sub-heading and unreliable for gear |",
           f"| Creatures (App. D) | {len(creatures)} | ~31 | |",
           f"| Gods/pantheon rows | {len(gods)} | — | row-pattern match; needs review before use |",
           "", "## Chapter text", "", "| File | Words |", "|---|---|"]
    for f in sorted((EXT / "chapters").glob("*.md")):
        out.append(f"| chapters/{f.name} | {len(re.findall(r'\w+', f.read_text(encoding='utf-8'))):,} |")
    out += ["", "## Known gaps and quality notes", "",
            "- The PDF's text layer has OCR-style letter spacing; `extract_phb.py` repairs most of it with a dictionary-based "
            "joiner, but stray splits (e.g. `them selves`) and a few misreads remain (`Cloud kill` is fixed by hand in `parse_spells.py`).",
            "- Spell descriptions for **Control Weather** and **Trap the Soul**, and the **Variant Human** trait block, are not in the text layer.",
            "- The PDF has 294 pages versus 317 printed pages; `pdf-page` markers are 0-based PDF indexes, not printed page numbers.",
            "- Chapter 5's first page (starting equipment/wealth) is not present as text.",
            "- Table pages use content-stream order; multi-column tables (class tables, spell slot tables) are kept as text rows.",
            "- Apostrophes and dashes appear as `’`/`—` after cleanup; the source uses a private glyph for both."]
    (EXT / "REPORT.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out[:22]))


if __name__ == "__main__":
    main()
