import { writeFileSync } from "node:fs";
import { startTurn } from "@/engine/combat";
import { planMonsterTurn } from "@/lib/combat/ai";
import { monsterStats } from "@/lib/combat/profiles";
import { resolveAttackAction, type Cmb } from "@/lib/combat/rules";
import { prisma } from "@/lib/prisma";

/** Runs every stat block through the combat code: parse it, plan a turn against a dummy hero, and resolve each attack once. */
const dummy = (over: Partial<Cmb> = {}): Cmb => ({
  id: "t", kind: "character", name: "Dummy", ac: 14, hp: 500, maxHp: 500, tempHp: 0, speed: 30, initiative: 0, dexMod: 0, conditions: [], hidden: false,
  surprised: false, defeated: false, deathSaves: { successes: 0, failures: 0 }, turn: startTurn(30), x: 6, y: 5, defenses: {}, ...over,
});

(async () => {
  const all = await prisma.creature.findMany({ orderBy: { name: "asc" } });
  const problems: { name: string; issue: string }[] = [];
  let ok = 0;
  for (const m of all) {
    try {
      const s = monsterStats(m);
      const issues: string[] = [];
      if (!s.attacks.length) issues.push(/Attack|attack/.test(m.text) ? "has attack text the parser did not read" : "no weapon attacks (spellcaster or special)");
      if (!(s.ac >= 1 && s.ac <= 30)) issues.push(`odd AC ${s.ac}`);
      if (!(s.hp >= 1)) issues.push(`odd HP ${s.hp}`);
      if (!(s.speed >= 0)) issues.push("no speed");
      if (s.attacks.length) {
        const self = { id: "m", name: m.name, x: 5, y: 5, turn: { ...startTurn(s.speed), movement: s.speed }, attacksPerAction: s.attacksPerAction };
        const plan = planMonsterTurn({ self, profiles: s.attacks, foes: [{ id: "t", name: "Dummy", ac: 14, hp: 500, x: 12, y: 5, defeated: false, hidden: false }], occupied: new Set(), width: 30, height: 30 });
        if (plan.kind === "pass") issues.push(`planner passes: ${plan.note}`);
        const attacker: Cmb = { ...dummy({ id: "m", name: m.name, kind: "monster", x: 5, y: 5 }), speed: s.speed, attacksPerAction: s.attacksPerAction };
        for (const a of s.attacks) {
          const out = resolveAttackAction(attacker, dummy(), a, { withinFiveFeet: a.melee, distanceFeet: a.melee ? 5 : 30, skipEconomy: true });
          if (!out.lines.length) issues.push(`attack ${a.name} produced no result`);
        }
      }
      if (issues.length) issues.forEach((issue) => problems.push({ name: m.name, issue }));
      else ok++;
    } catch (e) {
      problems.push({ name: m.name, issue: `threw: ${(e as Error).message}` });
    }
  }
  const lines = [
    "# Monster audit", "", "Generated by `pnpm monsters:audit`. Every creature is parsed, a turn is planned for it against a dummy hero, and each attack is resolved once.", "",
    `**${ok} of ${all.length} creatures run cleanly.**`, "", ...(problems.length ? ["## Needs attention", "", ...problems.map((p) => `- ${p.name}: ${p.issue}`), ""] : []),
  ];
  writeFileSync("docs/monster-audit.md", lines.join("\n"));
  console.log(`${ok}/${all.length} clean; ${problems.length} issues`);
  const kinds: Record<string, number> = {};
  for (const p of problems) kinds[p.issue.split(":")[0]] = (kinds[p.issue.split(":")[0]] ?? 0) + 1;
  console.log(kinds);
  await prisma.$disconnect();
})();
