import { writeFileSync } from "node:fs";
import { parseSpellEffect } from "@/engine/spells/effects";
import { automationMode } from "@/lib/combat/spellRules";
import { prisma } from "@/lib/prisma";

/** Which spells the combat engine can resolve by itself, and which are narrated by the DM. Writes docs/spell-automation.md. */
(async () => {
  const spells = await prisma.spell.findMany({ where: { campaignId: null }, orderBy: [{ level: "asc" }, { name: "asc" }] });
  const rows = spells.map((s) => {
    const e = parseSpellEffect(s);
    const mode = automationMode(s.index, e);
    const needs = mode === "narrated" ? "DM adjudicates" : "";
    return { s, e, mode, needs };
  });
  const by: Record<string, number> = {};
  for (const r of rows) by[r.mode] = (by[r.mode] ?? 0) + 1;
  const automated = rows.length - (by.narrated ?? 0);
  const pct = Math.round((automated / rows.length) * 100);

  const lines = [
    "# Spell automation coverage",
    "",
    "Generated by `pnpm spells:coverage`. A spell is *automated* when combat can roll its attack, saving throw, damage, healing or lasting bonus. The rest are cast (slot spent, concentration tracked, logged) and the DM narrates the effect.",
    "",
    `**${automated} of ${rows.length} spells automated (${pct}%).**`,
    "",
    "| Mode | Spells |",
    "| --- | ---: |",
    ...Object.entries(by).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`),
    "",
    "## Narrated spells",
    "",
    rows.filter((r) => r.mode === "narrated").map((r) => `${r.s.name} (${r.s.level === 0 ? "cantrip" : r.s.level})`).join(", "),
    "",
  ];
  writeFileSync("docs/spell-automation.md", lines.join("\n"));
  console.log(`${automated}/${rows.length} automated (${pct}%)`, by);
  await prisma.$disconnect();
})();
