export const featuresAt = (classIndex: string, level: number): FeatureGrant[] =>
  (CLASS_FEATURES[classIndex] ?? []).filter((f) => f.level === level);

export const subclassFeaturesAt = (subclassIndex: string, level: number): FeatureGrant[] =>
  (SUBCLASS_FEATURES[subclassIndex] ?? []).filter((f) => f.level === level);

const bare = (name: string) => name.replace(/ \(.*\)$/, "");

/** Every class and subclass feature the character has reached, newest levels included. */
export function featuresKnown(classes: ClassLevel[]): { name: string; source: string; automated: boolean }[] {
  const seen = new Set<string>();
  const out: { name: string; source: string; automated: boolean }[] = [];
  for (const c of classes) {
    for (const f of CLASS_FEATURES[c.classIndex] ?? []) {
      if (f.level > c.level) continue;
      const key = `${c.classIndex}:${f.name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ name: f.name, source: c.classIndex, automated: AUTOMATED_FEATURES.has(bare(f.name)) });
    }
    if (!c.subclassIndex) continue;
    for (const f of SUBCLASS_FEATURES[c.subclassIndex] ?? []) {
      if (f.level > c.level) continue;
      const key = `${c.subclassIndex}:${f.level}:${f.name}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ name: f.name, source: c.subclassIndex, automated: AUTOMATED_FEATURES.has(bare(f.name)) });
    }
  }
  return out;
}
